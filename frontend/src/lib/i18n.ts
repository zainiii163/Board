export type Locale = "en" | "ur";

export function pickLocalized(locale: Locale, en: string, ur?: string): string {
  if (locale === "ur" && ur?.trim()) return ur;
  return en;
}

export function pickLocalizedList(locale: Locale, en: string[], ur?: string[]): string[] {
  if (locale === "ur" && ur && ur.length > 0) return ur;
  return en;
}

export type LocalizedStep = { title: string; content: string };

export function pickLocalizedSteps(
  locale: Locale,
  en: LocalizedStep[],
  ur?: LocalizedStep[],
): LocalizedStep[] {
  if (locale === "ur" && ur && ur.length > 0) return ur;
  return en;
}

